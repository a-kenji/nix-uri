/// Nix reads an empty, blank or control-character input as a relative path.
#[rstest]
#[case("")]
#[case(" ")]
#[case("\t")]
#[case("\u{1}")]
fn blank_input_is_a_relative_path(#[case] input: &str) {
    rejects(input, Context::Standalone, Rejected::RelativePath);
    let parsed = FlakeRef::parse(input, Context::FlakeInput).unwrap();
    assert_eq!(
        attrs_json(&parsed),
        format!(
            r#"{{"path":{},"type":"path"}}"#,
            serde_json::to_string(input).unwrap()
        )
    );
}

/// `parseFlakeRefWithFragment`: flake-input rules plus a decoded fragment. The values are
/// those of the reference without the fragment.
#[rstest]
#[case(
    "github:NixOS/nixpkgs#hello",
    r#"{"owner":"NixOS","repo":"nixpkgs","type":"github"}"#,
    "github:NixOS/nixpkgs",
    Some("hello")
)]
#[case(
    "nixpkgs#hello",
    r#"{"id":"nixpkgs","type":"indirect"}"#,
    "flake:nixpkgs",
    Some("hello")
)]
#[case(
    "./foo#bar",
    r#"{"path":"./foo","type":"path"}"#,
    "path:./foo",
    Some("bar")
)]
#[case(
    "github:o/r?dir=lib#x.y",
    r#"{"dir":"lib","owner":"o","repo":"r","type":"github"}"#,
    "github:o/r?dir=lib",
    Some("x.y")
)]
#[case(
    "github:o/r#default%20package",
    r#"{"owner":"o","repo":"r","type":"github"}"#,
    "github:o/r",
    Some("default package")
)]
#[case(
    "github:o/r#",
    r#"{"owner":"o","repo":"r","type":"github"}"#,
    "github:o/r",
    None
)]
fn with_fragment(
    #[case] input: &str,
    #[case] attrs: &str,
    #[case] display: &str,
    #[case] fragment: Option<&str>,
) {
    let (parsed, parsed_fragment) = FlakeRef::parse_with_fragment(input).unwrap();
    assert_eq!(attrs_json(&parsed), attrs);
    assert_eq!(parsed.to_string(), display);
    assert_eq!(parsed_fragment.as_deref(), fragment);
}

/// An empty fragment is dropped.
#[rstest]
fn empty_fragment_is_not_a_fragment(
    #[values(Context::Standalone, Context::FlakeInput)] context: Context,
) {
    accepts(
        "github:o/r#",
        context,
        r#"{"owner":"o","repo":"r","type":"github"}"#,
        "github:o/r",
    );
}

