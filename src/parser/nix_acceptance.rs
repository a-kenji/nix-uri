//! What Nix accepts, and what it parses an accepted reference into, per [`Context`].
//! Every row was generated from Nix 2.35.3: `builtins.parseFlakeRef` and
//! `builtins.flakeRefToString` for [`Context::Standalone`], and a flake input's
//! `original` lock entry for [`Context::FlakeInput`].
//!
//! Accepted rows pin the attributes, as the JSON `builtins.parseFlakeRef` returns, and
//! the `Display` output. The rejected rows pin the error nix-uri reports.
//!
//! `verifyCommit`, `keytype`, `publicKey` and `publicKeys` are left out: Nix rejects them
//! unless the `verified-fetches` experimental feature is enabled, which nix-uri does not
//! model.
use rstest::rstest;

use crate::{Context, FlakeRef, NixUriError, UnsupportedReason};

#[derive(Debug, Clone, Copy)]
pub(super) enum Rejected {
    Fragment,
    RelativePath,
    ScpStyleUrl,
    Param,
    InvalidRef,
    InvalidRev,
    InvalidHost,
    /// Any other field with a bad value.
    InvalidValue,
    DuplicateRef,
    DuplicateRev,
    FieldConflict,
    UriType,
    TransportLayer,
    TooManySegments,
    Authority,
    /// A malformed URL that is not one of the specific shapes above.
    Malformed,
}

impl Rejected {
    fn matches(self, err: &NixUriError) -> bool {
        use UnsupportedReason as R;
        match self {
            Self::Fragment => matches!(err, NixUriError::Unsupported(R::Fragment { .. })),
            Self::RelativePath => {
                matches!(err, NixUriError::Unsupported(R::RelativePath { .. }))
            }
            Self::ScpStyleUrl => matches!(err, NixUriError::Unsupported(R::ScpStyleUrl { .. })),
            Self::Param => matches!(err, NixUriError::Unsupported(R::Param { .. })),
            Self::InvalidRef => matches!(err, NixUriError::InvalidValue { field: "ref", .. }),
            Self::InvalidRev => matches!(err, NixUriError::InvalidValue { field: "rev", .. }),
            Self::InvalidHost => matches!(err, NixUriError::InvalidValue { field: "host", .. }),
            Self::InvalidValue => matches!(err, NixUriError::InvalidValue { .. }),
            Self::DuplicateRef => matches!(err, NixUriError::DuplicateField { field: "ref" }),
            Self::DuplicateRev => matches!(err, NixUriError::DuplicateField { field: "rev" }),
            Self::FieldConflict => matches!(err, NixUriError::FieldConflict { .. }),
            Self::UriType => matches!(err, NixUriError::Unsupported(R::UriType { .. })),
            Self::TransportLayer => {
                matches!(err, NixUriError::Unsupported(R::TransportLayer { .. }))
            }
            Self::TooManySegments => matches!(err, NixUriError::TooManyIndirectSegments { .. }),
            Self::Authority => matches!(err, NixUriError::Unsupported(R::Authority { .. })),
            Self::Malformed => matches!(
                err,
                NixUriError::InvalidUrl(_) | NixUriError::Unsupported(R::MissingParameter { .. })
            ),
        }
    }
}

fn attrs_json(flake_ref: &FlakeRef) -> String {
    serde_json::to_string(&flake_ref.to_attrs()).unwrap()
}

fn accepts(input: &str, context: Context, attrs: &str, display: &str) {
    let parsed = FlakeRef::parse(input, context)
        .unwrap_or_else(|e| panic!("{input:?} in {context:?}: expected accept, got {e:?}"));
    assert_eq!(attrs_json(&parsed), attrs, "{input:?} in {context:?}");
    assert_eq!(parsed.to_string(), display, "{input:?} in {context:?}");
}

fn rejects(input: &str, context: Context, kind: Rejected) {
    match FlakeRef::parse(input, context) {
        Ok(parsed) => panic!("{input:?} in {context:?}: expected {kind:?}, got {parsed:?}"),
        Err(err) => assert!(
            kind.matches(&err),
            "{input:?} in {context:?}: expected {kind:?}, got {err:?}"
        ),
    }
}

